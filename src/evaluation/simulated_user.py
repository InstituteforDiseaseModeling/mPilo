from langchain.prompts import (
    ChatPromptTemplate,
    HumanMessagePromptTemplate,
    MessagesPlaceholder,
)
from langchain.schema import SystemMessage
from langchain.chains import LLMChain
from langchain.memory import ConversationBufferMemory
from langchain_openai import ChatOpenAI


class User:
    """Class to create a simulated user for conversation simulation."""

    def __init__(self, prompt):
        """Initialize the class.

        Parameters
        ----------
        prompt : str
            The system prompt describing the characteristics of the user.
        """
        prompt = ChatPromptTemplate.from_messages(
            [
                SystemMessage(content=prompt),
                MessagesPlaceholder(variable_name="chat_history"),
                HumanMessagePromptTemplate.from_template("{human_input}"),
            ]
        )
        self.memory = ConversationBufferMemory(memory_key="chat_history", return_messages=True)
        llm = ChatOpenAI()
        self.chain = LLMChain(
            llm=llm,
            prompt=prompt,
            verbose=True,
            memory=self.memory,
        )

    def __call__(self, human_input):
        """Allow the class to be called like a function.

        Parameters
        ----------
        prompt : str
            The system prompt describing the characteristics of the user.

        Returns
        -------
        str
            Returns string output generated by the LLM.
        """
        return self.chain.predict(human_input=human_input)
